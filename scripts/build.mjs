#!/usr/bin/env node
/**
 * Build pipeline:
 *  1. Bundle the browser code (MCP App widget, connect page, account page) and inline it into
 *     src/generated/assets.ts so the Worker and the CLI serve identical, self-contained HTML.
 *  2. Bundle the CLI (stdio MCP server + `login`) and the library entry for npm.
 */
import { build } from 'esbuild';
import { mkdir, readFile, writeFile, chmod } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { spawnSync } from 'node:child_process';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const pkg = JSON.parse(await readFile(join(root, 'package.json'), 'utf8'));
const browserOnly = process.argv.includes('--assets');

async function bundleBrowser(entry) {
  const out = await build({
    entryPoints: [join(root, entry)],
    bundle: true,
    format: 'esm',
    platform: 'browser',
    target: ['es2022'],
    minify: true,
    legalComments: 'none',
    write: false,
  });
  return out.outputFiles[0].text;
}

/** Inline scripts cannot contain a literal closing script tag. */
const inlineSafe = (js) => js.replace(/<\/script/gi, '<\\/script').replace(/<!--/g, '<\\!--');

const [widgetJs, connectJs, accountJs, widgetTpl] = await Promise.all([
  bundleBrowser('src/web/widget-client.ts'),
  bundleBrowser('src/web/connect-client.ts'),
  bundleBrowser('src/web/account-client.ts'),
  readFile(join(root, 'src/web/widget.html'), 'utf8'),
]);
if (!widgetTpl.includes('/*WIDGET_JS*/')) throw new Error('widget.html is missing the /*WIDGET_JS*/ placeholder');
const widgetHtml = widgetTpl.replace('/*WIDGET_JS*/', () => inlineSafe(widgetJs));

await mkdir(join(root, 'src/generated'), { recursive: true });
await writeFile(
  join(root, 'src/generated/assets.ts'),
  `// Generated by scripts/build.mjs. Do not edit.\n` +
    `export const WIDGET_HTML: string = ${JSON.stringify(widgetHtml)};\n` +
    `export const CONNECT_JS: string = ${JSON.stringify(inlineSafe(connectJs))};\n` +
    `export const ACCOUNT_JS: string = ${JSON.stringify(inlineSafe(accountJs))};\n`,
);
console.log(`assets: widget ${(widgetHtml.length / 1024).toFixed(1)} KB, connect ${(connectJs.length / 1024).toFixed(1)} KB, account ${(accountJs.length / 1024).toFixed(1)} KB`);

if (!browserOnly) {
  const external = Object.keys(pkg.dependencies ?? {});
  const common = { bundle: true, platform: 'node', format: 'esm', target: ['node20'], external, sourcemap: false, legalComments: 'none' };
  await build({ ...common, entryPoints: [join(root, 'src/cli.ts')], outfile: join(root, 'dist/cli.js'), banner: { js: '#!/usr/bin/env node' } });
  await chmod(join(root, 'dist/cli.js'), 0o755);
  await build({ ...common, entryPoints: [join(root, 'src/index.ts')], outfile: join(root, 'dist/index.js') });
  const tsc = spawnSync(process.execPath, [join(root, 'node_modules/typescript/bin/tsc'), '-p', join(root, 'tsconfig.build.json')], { stdio: 'inherit' });
  if (tsc.status !== 0) process.exit(tsc.status ?? 1);
  console.log('dist: cli.js, index.js, types/');
}
